import { Badge } from "./ui";
import { STATUS_LABELS, STATUS_TONE, type AppStatus } from "@/lib/constants";
import { formatDate, safeJson } from "@/lib/utils";

export function StatusTimeline({ history }: { history: { id: string; fromStatus: string | null; toStatus: string; reason: string; createdAt: Date; actorName: string | null }[] }) {
  if (history.length === 0) return <p className="text-sm text-muted">No status changes yet.</p>;
  return (
    <ol className="relative space-y-4 border-l border-line pl-5">
      {history.map((h) => (
        <li key={h.id} className="relative">
          <span className="absolute -left-[25px] top-1.5 h-2.5 w-2.5 rounded-full border-2 border-white bg-navy-700 ring-1 ring-line" aria-hidden />
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={STATUS_TONE[h.toStatus as AppStatus]}>{STATUS_LABELS[h.toStatus as AppStatus] ?? h.toStatus}</Badge>
            <span className="text-xs text-muted">{formatDate(h.createdAt, true)}</span>
          </div>
          <p className="mt-1 text-sm text-ink">{h.reason}</p>
          <p className="text-xs text-muted">{h.actorName ?? "System"}</p>
        </li>
      ))}
    </ol>
  );
}

export function PriorityExplainer({ level, score, factors }: { level: string; score: number; factors: string }) {
  const f = safeJson<{ factor: string; points: number }[]>(factors, []);
  return (
    <div>
      <div className="flex items-center gap-2">
        <Badge tone={level === "HIGH" ? "danger" : level === "MEDIUM" ? "warning" : "info"}>{level.charAt(0) + level.slice(1).toLowerCase()} review priority</Badge>
        <span className="text-sm text-muted">score {score}</span>
      </div>
      {f.length > 0 ? (
        <ul className="mt-2 space-y-0.5 text-xs text-muted">
          {f.map((x) => (
            <li key={x.factor}>
              +{x.points} · {x.factor}
            </li>
          ))}
        </ul>
      ) : (
        <p className="mt-1 text-xs text-muted">No unresolved weighted findings.</p>
      )}
      <p className="mt-1.5 text-xs text-muted">Orders human review only — not a probability of fraud or a regulatory outcome.</p>
    </div>
  );
}

export function RunSummary({ run }: { run: { summary: string; summarySource: string; recommendations: string; aiMode: string; aiProvider: string; aiModel: string; rulesetVersion: string; startedAt: Date; durationMs: number; findingCount: number } }) {
  const recs = safeJson<string[]>(run.recommendations, []);
  const mock = run.summarySource === "ai_mock";
  return (
    <div>
      <div className="flex flex-wrap items-center gap-2 text-xs text-muted">
        <span>Run {formatDate(run.startedAt, true)}</span>
        <span>· ruleset {run.rulesetVersion}</span>
        <span>· {run.findingCount} finding(s)</span>
        <span>· {(run.durationMs / 1000).toFixed(1)}s</span>
        <Badge tone={run.aiMode === "LIVE" ? "success" : run.aiMode === "DEGRADED" ? "warning" : "neutral"} className={run.aiMode === "DEMO" ? "bg-demo-bg text-demo ring-demo/20" : undefined}>
          {run.aiMode === "LIVE" ? `AI: ${run.aiProvider} · ${run.aiModel}` : run.aiMode === "DEGRADED" ? "AI degraded — demo fallback used" : "DEMO MODE — no AI model called"}
        </Badge>
      </div>
      {run.summary && (
        <div className={mock ? "mt-3 rounded-md bg-demo-bg p-3" : "mt-3 rounded-md bg-info-bg p-3"}>
          <div className={mock ? "text-xs font-medium text-demo" : "text-xs font-medium text-info"}>{mock ? "Summary — simulated (DEMO MODE)" : "Summary — generated by live AI model"}</div>
          <p className="mt-1 text-sm text-ink">{run.summary}</p>
          {recs.length > 0 && (
            <ul className="mt-2 list-disc space-y-0.5 pl-5 text-sm text-ink">
              {recs.map((r) => (
                <li key={r}>{r}</li>
              ))}
            </ul>
          )}
        </div>
      )}
    </div>
  );
}

export function ExtractedText({ doc }: { doc: { originalName: string; pages: { pageNumber: number; text: string; method: string; ocrConfidence: number | null }[]; fields: { id: string; field: string; value: string; page: number | null; source: string; evidence: string }[] } }) {
  return (
    <details className="rounded-md border border-line bg-white">
      <summary className="cursor-pointer px-3 py-2 text-sm font-medium">{doc.originalName}</summary>
      <div className="space-y-3 border-t border-line p-3">
        {doc.fields.length > 0 && (
          <table className="w-full text-sm">
            <thead>
              <tr className="text-left text-xs text-muted">
                <th className="pb-1 pr-2 font-medium">Field</th>
                <th className="pb-1 pr-2 font-medium">Value</th>
                <th className="pb-1 font-medium">Source</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-line">
              {doc.fields.map((f) => (
                <tr key={f.id}>
                  <td className="py-1 pr-2 text-muted">{f.field}</td>
                  <td className="py-1 pr-2 break-all">{f.value}</td>
                  <td className="py-1 text-xs text-muted">{f.source === "parser" ? `parser · p.${f.page ?? "?"}` : f.source === "ai_live" ? `live AI · p.${f.page ?? "?"}` : "demo"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        {doc.pages.map((p) => (
          <div key={p.pageNumber}>
            <div className="mb-1 flex items-center gap-2 text-xs text-muted">
              <span>Page {p.pageNumber}</span>
              <Badge tone={p.method === "ocr" ? "info" : p.method === "none" ? "danger" : "neutral"}>{p.method === "ocr" ? "OCR" : p.method === "none" ? "No text" : "PDF text layer"}</Badge>
              {p.ocrConfidence !== null && <span title="Tesseract engine confidence — not a calibrated probability">engine confidence {Math.round(p.ocrConfidence)}</span>}
            </div>
            <pre className="max-h-64 overflow-auto whitespace-pre-wrap rounded bg-paper p-2 font-mono text-xs text-ink">{p.text || "(no text)"}</pre>
          </div>
        ))}
      </div>
    </details>
  );
}

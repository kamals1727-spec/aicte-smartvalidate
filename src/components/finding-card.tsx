import { Badge } from "./ui";
import { cn, formatDate } from "@/lib/utils";
import {
  FINDING_RESULTS,
  FINDING_SOURCE_LABELS,
  REVIEW_STATUSES,
  REVIEW_TONE,
  SEVERITY_TONE,
  type FindingResult,
  type ReviewStatus,
  type Severity,
} from "@/lib/constants";

export interface FindingView {
  id: string;
  refNo: string;
  ruleCode: string;
  category: string;
  severity: string;
  result: string;
  field: string | null;
  page: number | null;
  actualValue: string;
  expectedValue: string;
  explanation: string;
  recommendedAction: string;
  evidence: string;
  humanReviewRequired: boolean;
  source: string;
  aiExplanation: string;
  aiExplanationSource: string;
  reviewStatus: string;
  reviewReason: string;
  reviewedAt: Date | null;
}

const RAIL: Record<string, string> = {
  deterministic: "bg-navy-700",
  ai_live: "bg-action",
  ai_mock: "bg-demo",
};

const sevLabel = (s: string) => s.charAt(0) + s.slice(1).toLowerCase();

/**
 * A finding, with its provenance made visible: the left rail colour and label say
 * whether a deterministic rule, a live AI model or simulated demo output produced it,
 * and a separate band below shows any officer review. These states are never merged.
 */
export function FindingCard({ f, documentName, children, anchor }: { f: FindingView; documentName?: string | null; children?: React.ReactNode; anchor?: boolean }) {
  return (
    <article id={anchor ? f.refNo : undefined} className="overflow-hidden rounded-lg border border-line bg-white">
      <div className="flex">
        <div className={cn("w-1.5 shrink-0", RAIL[f.source] ?? "bg-slate-300")} aria-hidden />
        <div className="min-w-0 flex-1 p-4">
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={SEVERITY_TONE[f.severity as Severity]}>{sevLabel(f.severity)}</Badge>
            <Badge tone={f.source === "ai_mock" ? "neutral" : f.source === "ai_live" ? "info" : "navy"} className={f.source === "ai_mock" ? "bg-demo-bg text-demo ring-demo/20" : undefined}>
              {FINDING_SOURCE_LABELS[f.source] ?? f.source}
            </Badge>
            <span className="text-xs text-muted">
              {f.refNo} · {f.ruleCode} · {f.category}
            </span>
          </div>
          <p className="mt-2 font-medium text-ink">{f.explanation}</p>
          <dl className="mt-3 grid gap-x-6 gap-y-2 text-sm sm:grid-cols-2">
            <div>
              <dt className="text-xs text-muted">Result</dt>
              <dd>{FINDING_RESULTS[f.result as FindingResult] ?? f.result}</dd>
            </div>
            <div>
              <dt className="text-xs text-muted">Affected</dt>
              <dd className="break-words">
                {documentName ?? "Application form"}
                {f.field ? ` · ${f.field}` : ""}
                {f.page ? ` · page ${f.page}` : ""}
              </dd>
            </div>
            <div>
              <dt className="text-xs text-muted">Found (actual)</dt>
              <dd className="break-words">{f.actualValue || "—"}</dd>
            </div>
            <div>
              <dt className="text-xs text-muted">Expected</dt>
              <dd className="break-words">{f.expectedValue || "—"}</dd>
            </div>
          </dl>
          {f.evidence && (
            <div className="mt-3">
              <div className="text-xs text-muted">Evidence</div>
              <blockquote className="mt-1 break-words rounded border-l-2 border-line bg-paper px-3 py-1.5 font-mono text-[12.5px] text-ink">{f.evidence}</blockquote>
            </div>
          )}
          <p className="mt-3 text-sm">
            <span className="text-muted">Recommended action: </span>
            {f.recommendedAction}
          </p>
          {f.aiExplanation && (
            <div className={cn("mt-3 rounded-md px-3 py-2 text-sm", f.aiExplanationSource === "ai_mock" ? "bg-demo-bg" : "bg-info-bg")}>
              <div className={cn("text-xs font-medium", f.aiExplanationSource === "ai_mock" ? "text-demo" : "text-info")}>
                {f.aiExplanationSource === "ai_mock" ? "Plain-language explanation — DEMO MODE, simulated (no AI model called)" : "Plain-language explanation — generated by live AI model"}
              </div>
              <p className="mt-0.5 text-ink">{f.aiExplanation}</p>
            </div>
          )}
          {f.humanReviewRequired && f.reviewStatus === "OPEN" && <p className="mt-2 text-xs text-warn">Human review required before any conclusion is drawn.</p>}
        </div>
      </div>
      {f.reviewStatus !== "OPEN" && (
        <div className="flex border-t border-line">
          <div className={cn("w-1.5 shrink-0", REVIEW_TONE[f.reviewStatus as ReviewStatus] === "success" ? "bg-ok" : REVIEW_TONE[f.reviewStatus as ReviewStatus] === "danger" ? "bg-bad" : "bg-warn")} aria-hidden />
          <p className="px-4 py-2.5 text-sm">
            <span className="font-medium">Officer review: {REVIEW_STATUSES[f.reviewStatus as ReviewStatus]}</span>
            {f.reviewReason && <span className="text-muted"> — {f.reviewReason}</span>}
            {f.reviewedAt && <span className="ml-1 text-xs text-muted">({formatDate(f.reviewedAt, true)})</span>}
          </p>
        </div>
      )}
      {children && <div className="border-t border-line bg-paper px-4 py-3">{children}</div>}
    </article>
  );
}

// DEMO MODE provider. Deterministic, derived from the real extracted text and the real
// deterministic findings — never random, and always labelled as simulated in the UI.
import type { DocumentAnalysis, FindingsSummary } from "./schemas";
import type { ParsedField } from "../extraction/fields";

const TYPE_KEYWORDS: { code: string; words: RegExp }[] = [
  { code: "ACCREDITATION_CERT", words: /accreditation/i },
  { code: "NOC", words: /no\s*objection|\bnoc\b/i },
  { code: "AFFIDAVIT", words: /affidavit|undertaking/i },
  { code: "FEE_RECEIPT", words: /fee\s*receipt|transaction\s*ref|amount\s*paid/i },
  { code: "FIRE_SAFETY_CERT", words: /fire\s*safety/i },
  { code: "BUILDING_CERT", words: /building\s*(completion|stability)|structural\s*stability/i },
  { code: "LAND_DOCUMENT", words: /land\s*(registration|record|deed)|sale\s*deed/i },
  { code: "FACULTY_LIST", words: /faculty\s*(list|details|roster)/i },
  { code: "LAB_PHOTO", words: /laborator/i },
];

export function mockDocumentAnalysis(input: {
  declaredDocType: string;
  text: string;
  parsed: ParsedField[];
}): DocumentAnalysis {
  const guess = TYPE_KEYWORDS.find((k) => k.words.test(input.text))?.code ?? "unknown";
  const matches: DocumentAnalysis["matches_declared_type"] =
    guess === "unknown" ? "unclear" : guess === input.declaredDocType ? "yes" : "no";
  const observations: DocumentAnalysis["observations"] = [];
  if (matches === "no") {
    observations.push({
      category: "document_type_mismatch",
      description: `Keyword heuristics suggest this file may be a ${guess.replaceAll("_", " ").toLowerCase()}, but it was uploaded as ${input.declaredDocType.replaceAll("_", " ").toLowerCase()}.`,
      evidence: "Keyword match on extracted text (demo heuristic).",
      recommended_action: "Check that the correct file was uploaded against this checklist item.",
    });
  }
  return {
    document_type: guess,
    matches_declared_type: matches,
    extracted_fields: input.parsed.map((f) => ({ field: f.field, value: f.value, page: f.page, evidence: f.evidence })),
    observations,
    limitations: [
      "DEMO MODE — no AI model was called. Output generated by deterministic keyword rules.",
      "Signatures, seals and issuing-authority records cannot be verified from extracted text.",
    ],
  };
}

const EXPLAIN: Record<string, (f: MockFinding) => string> = {
  REQUIRED_DOCUMENT: (f) =>
    `A document that the configured checklist marks as mandatory for this category is missing (${f.expected}). Upload it if it applies to this application, or explain why it does not.`,
  REQUIRED_FIELD: (f) => `A required application field is empty (${f.field || f.expected}). Complete the field before submission.`,
  DOCUMENT_EXPIRY: (f) =>
    f.result === "UNABLE_TO_DETERMINE"
      ? "No expiry date could be read from this document, so validity cannot be confirmed automatically. A reviewer should check it manually."
      : `The validity date read from the document (${f.actual}) has passed. Request an updated certificate or manual verification.`,
  DATE_CONSISTENCY: () => "The dates on this document are internally inconsistent (for example, issued after its expiry). Please review the source document.",
  FIELD_MATCH: (f) =>
    `The value on the document (${f.actual}) differs from what the application declares (${f.expected}). Please review the mismatch — it may be a typo or the wrong file.`,
  INSTITUTION_RECORD_MATCH: (f) =>
    `The application details (${f.actual}) do not match the institution record held in the demo database (${f.expected}).`,
  DUPLICATE_FILE: () => "The same file (identical SHA-256 hash) appears more than once. Check whether the duplicate upload was intentional.",
  EXTRACTION_QUALITY: () => "Little or no readable text could be extracted, so automated checks on this document are incomplete. Manual reading is required.",
  PAYMENT_MATCH: (f) => `The payment details could not be reconciled with the synthetic payment ledger (${f.actual}). Verify the transaction reference and amount.`,
  INTAKE_CONSISTENCY: () => "The intake figures are inconsistent with the selected application category. Please review the approved and proposed intake.",
  MANUAL_VERIFICATION: () => "Signatures, seals and the original issuing authority cannot be verified automatically; an official must verify these manually.",
  AI_OBSERVATION: (f) => f.explanation,
};

export interface MockFinding {
  ref: string;
  type: string;
  severity: string;
  result: string;
  field: string;
  expected: string;
  actual: string;
  explanation: string;
}

export function mockFindingsSummary(input: { applicationRef: string; findings: MockFinding[] }): FindingsSummary {
  const by = (s: string) => input.findings.filter((f) => f.severity === s).length;
  const total = input.findings.length;
  const summary =
    total === 0
      ? `No deterministic rule raised an issue for ${input.applicationRef}. This does not establish compliance: authenticity and source verification still require human review.`
      : `${input.applicationRef} has ${total} preliminary finding(s): ${by("CRITICAL")} critical, ${by("HIGH")} high, ${by("MEDIUM")} medium, ${by("LOW") + by("INFO")} low/informational. ` +
        `These were raised by configured rules and need human review before any conclusion is drawn.`;
  const recs: string[] = [];
  if (input.findings.some((f) => f.type === "REQUIRED_DOCUMENT")) recs.push("Ask the institution to upload the missing mandatory documents.");
  if (input.findings.some((f) => f.type === "DOCUMENT_EXPIRY" && f.result === "NOT_SATISFIED")) recs.push("Request current, valid certificates for expired documents.");
  if (input.findings.some((f) => f.type === "FIELD_MATCH" || f.type === "INSTITUTION_RECORD_MATCH")) recs.push("Seek clarification on name/ID mismatches against the institution record.");
  if (input.findings.some((f) => f.type === "PAYMENT_MATCH")) recs.push("Reconcile the payment reference with the fee ledger before scrutiny proceeds.");
  if (input.findings.some((f) => f.type === "DUPLICATE_FILE")) recs.push("Confirm whether duplicate uploads were intentional.");
  recs.push("Verify signatures, seals and issuing authorities manually.");
  return {
    summary,
    finding_explanations: input.findings.map((f) => ({
      finding_ref: f.ref,
      explanation: (EXPLAIN[f.type] ?? ((x: MockFinding) => x.explanation))(f),
    })),
    reviewer_recommendations: recs.slice(0, 6),
    limitations: ["DEMO MODE — simulated AI explanations generated from templates; no language model was called."],
  };
}

import { notFound } from "next/navigation";
import { eq } from "drizzle-orm";
import { requireActorPage } from "@/server/auth/actor";
import { canViewApplication } from "@/server/authz";
import { getDb, schema } from "@/server/db";
import { PageHeader } from "@/components/ui";
import { formatDate } from "@/lib/utils";

export const metadata = { title: "Demo certificate record" };

export default async function CertificatePage({ params }: { params: Promise<{ id: string }> }) {
  const actor = await requireActorPage();
  const { id } = await params;
  const db = getDb();
  const [row] = await db
    .select({ c: schema.certificateRecords, app: schema.applications, inst: schema.institutions, cat: schema.categories.name })
    .from(schema.certificateRecords)
    .innerJoin(schema.applications, eq(schema.applications.id, schema.certificateRecords.applicationId))
    .innerJoin(schema.institutions, eq(schema.institutions.id, schema.applications.institutionId))
    .innerJoin(schema.categories, eq(schema.categories.id, schema.applications.categoryId))
    .where(eq(schema.certificateRecords.id, id));
  if (!row || !canViewApplication(actor, row.app)) notFound();
  return (
    <>
      <PageHeader title="Certificate record" subtitle="A prototype record that follows an official decision. It is not, and must not be used as, an AICTE approval." />
      <div className="relative mx-auto max-w-3xl overflow-hidden rounded-lg border-4 border-double border-navy-700 bg-white p-10">
        <div className="pointer-events-none absolute inset-0 flex items-center justify-center" aria-hidden>
          <span className="-rotate-[24deg] select-none whitespace-nowrap text-5xl font-bold text-bad/15 sm:text-6xl">DEMO — NOT AN OFFICIAL AICTE CERTIFICATE</span>
        </div>
        <p className="text-center text-sm font-semibold text-bad">DEMO — NOT AN OFFICIAL AICTE CERTIFICATE</p>
        <h2 className="mt-6 text-center font-serif text-2xl font-semibold text-navy-900">Record of approval decision (prototype)</h2>
        <dl className="relative mt-8 grid gap-4 text-sm sm:grid-cols-2">
          <div><dt className="text-muted">Certificate record reference</dt><dd className="font-medium">{row.c.certificateRef}</dd></div>
          <div><dt className="text-muted">Application</dt><dd className="font-medium">{row.app.refNo}</dd></div>
          <div><dt className="text-muted">Institution (synthetic)</dt><dd>{row.inst.name} · {row.inst.refId}</dd></div>
          <div><dt className="text-muted">Category</dt><dd>{row.cat}</dd></div>
          <div><dt className="text-muted">Recorded issuing authority</dt><dd>{row.c.issuingAuthority}</dd></div>
          <div><dt className="text-muted">Recorded on</dt><dd>{formatDate(row.c.createdAt, true)}</dd></div>
        </dl>
        <p className="relative mt-8 text-xs text-muted">
          Generated by an independent hackathon prototype after an authorized demo user recorded an official decision. No authenticity-verification mechanism is configured; this record has no legal standing.
        </p>
      </div>
    </>
  );
}
